#!/usr/bin/env python3
"""Generate compile_commands.json for ChessDev from its .pro settings.

Usage (from the project root, next to ChessDev.pro):
    python3 gen_compile_commands.py
    python3 gen_compile_commands.py --qt-inc /usr/include/x86_64-linux-gnu/qt5 --cxx g++

Edit the CONFIG section below if your setup differs.
"""
import argparse
import glob
import json
import os
import shlex

ap = argparse.ArgumentParser()
ap.add_argument("--root", default=os.getcwd(), help="project root (dir of ChessDev.pro)")
ap.add_argument("--cxx", default="g++")
ap.add_argument("--qt-inc", default="/usr/include/x86_64-linux-gnu/qt5",
                help="Qt include dir that contains QtCore/, QtGui/, QtWidgets/")
ap.add_argument("--benchmark-inc", default="/home/you/dev/benchmark/include")
args = ap.parse_args()

root = os.path.abspath(args.root)
qt = args.qt_inc

# ---- CONFIG: values taken from the .pro files --------------------------------
# Top-level DEFINES in ChessDev.pro (a subdirs project) do NOT propagate to the
# subprojects in qmake, so it is deliberately not applied here.
QT_DEFINES = ["-DQT_NO_DEBUG", "-DQT_WIDGETS_LIB", "-DQT_GUI_LIB", "-DQT_CORE_LIB"]
QT_INCLUDES = [f"-I{qt}", f"-I{qt}/QtWidgets", f"-I{qt}/QtGui", f"-I{qt}/QtCore"]

# (subdir, sources, flags)
projects = {
    # lib.pro: staticlib, QT += core gui widgets, C++20, release LTO flags.
    # Note: mainwindow.cpp includes ui_mainwindow.h, generated by uic from
    # mainwindow.ui. For clangd to resolve it, run `qmake && make` once
    # (in-source build) or `uic lib/mainwindow.ui -o lib/ui_mainwindow.h`.
    "lib": dict(
        sources=[os.path.join(root, "lib", s) for s in
                 ["mainwindow.cpp", "draggable.cpp", "board.cpp",
                  "search.cpp", "engine_worker.cpp"]],
        flags=["-pipe", "-O2", "-Wall", "-Wextra", "-fPIC", "-std=c++20",
               "-flto", "-fuse-linker-plugin", "-ffat-lto-objects"],
        defines=QT_DEFINES,
        includes=["-I."] + QT_INCLUDES,
    ),
    # app.pro: QT += core gui widgets, INCLUDEPATH += ../lib
    "app": dict(
        sources=[os.path.join(root, "app", "main.cpp")],
        flags=["-pipe", "-O2", "-Wall", "-Wextra", "-fPIC"],  # qmake default; no -std set
        defines=QT_DEFINES,
        includes=["-I.", "-I../lib"] + QT_INCLUDES,
    ),
    # test.pro: gtest + benchmark, C++20, -g, constexpr limit
    "test": dict(
        sources=[os.path.join(root, "test", "main.cpp")],
        flags=["-pipe", "-O2", "-Wall", "-Wextra", "-fPIC", "-g", "-std=c++20"],
        includes=["-I.", "-I../lib", f"-I{args.benchmark_inc}"],
    ),
}

entries = []
for sub, p in projects.items():
    directory = os.path.join(root, sub)
    for src in p["sources"]:
        obj = os.path.splitext(os.path.basename(src))[0] + ".o"
        cmd = [args.cxx, "-c"] + p["flags"] + p.get("defines", []) + p["includes"] + ["-o", obj, src]
        entries.append({
            "directory": directory,
            "command": " ".join(shlex.quote(c) for c in cmd),
            "file": src,
        })

out = os.path.join(root, "compile_commands.json")
with open(out, "w") as f:
    json.dump(entries, f, indent=2)
print(f"Wrote {len(entries)} entries to {out}")

